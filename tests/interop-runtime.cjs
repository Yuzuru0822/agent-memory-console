    assert.equal(deployed.mcpServers.unmanaged.command,'fixture-unmanaged');
    const connection=deployed.mcpServers['agent-console-bridge'];
    assert.equal(connection.type,'http'); assert.ok(connection.headers.Authorization.startsWith('Bearer '));
    let plan=await page.evaluate(()=>window.consoleApi.mcpPreview('claude',['demo'],false));
    await page.evaluate(id=>window.consoleApi.mcpApply(id,['demo']),plan.id);
    assert.equal(JSON.parse(fs.readFileSync(claudeFile,'utf8')).mcpServers.demo.headers.Authorization,'Bearer fixture-test-private-secret');

    assert.equal(JSON.stringify(first).includes('fixture-test-private-secret'),false);
    await application.evaluate(()=>{global.__interop.confirm=false;});
    await page.evaluate(id=>window.consoleApi.mcpApply(id,[]),first.id);
    assert.equal(fs.readFileSync(claudeFile,'utf8'),before,'native cancellation writes nothing');
    await application.evaluate(()=>{global.__interop.confirm=true;});
    await page.evaluate(id=>window.consoleApi.mcpApply(id,[]),first.id);

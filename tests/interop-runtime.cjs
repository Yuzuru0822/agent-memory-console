    await page.evaluate(()=>window.consoleApi.mcpSetVariable('FIXTURE_API_KEY','fixture-test-private-secret'));
    const manifest={version:1,servers:{demo:{transport:'http',url:'https://example.org/mcp',headers:{Authorization:'Bearer ${FIXTURE_API_KEY}'}}}};
    await page.evaluate(json=>window.consoleApi.mcpSaveTemplates(json),JSON.stringify(manifest));
    assert.equal(fs.readFileSync(path.join(root,'mcp/servers.json'),'utf8').includes('fixture-test-private-secret'),false);
    assert.deepEqual((await page.evaluate(()=>window.consoleApi.mcpSnapshot())).variableNames,['FIXTURE_API_KEY']);
    const bind=async(id,profile,file)=>{
      await application.evaluate((_,file)=>{global.__interop.file=file;},file);
      await page.evaluate(({id,profile})=>window.consoleApi.mcpBind(id,profile),{id,profile});
    };
    await bind('claude','claude',claudeFile); await bind('workbuddy','workbuddy',buddyFile);
    const first=await page.evaluate(()=>window.consoleApi.mcpPreview('claude',['demo'],true));

    assert.equal((await a2a('GetTask',{id:a2aId},'0.3')).error.code,-32009);
    assert.equal((await a2a('ListTasks',{})).result.tasks.length,2);
    const status=await page.evaluate(()=>window.consoleApi.bridgeSnapshot());

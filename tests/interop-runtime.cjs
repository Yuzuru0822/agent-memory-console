  const fixture = path.resolve(project, '../../work', `interop-runtime-${Date.now()}`);
  const home = path.join(fixture, 'home'), data = path.join(fixture, 'data'), root = path.join(fixture, 'repository');
  fs.mkdirSync(home, {recursive:true}); fs.mkdirSync(path.join(data, 'console-data'), {recursive:true}); fs.mkdirSync(root);
  await require('../dist-electron/electron/repository-git.js').initRepository(root);
  fs.writeFileSync(path.join(data, 'console-data/config.json'), JSON.stringify({version:1,agents:{},repository:{root,agentIds:[],memoryFolders:{},automation:{enabled:false,intervalSeconds:60,cleanupEnabled:false,retentionDays:30,minBackups:20}}}));

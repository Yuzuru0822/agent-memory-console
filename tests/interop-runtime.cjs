    assert.ok(!JSON.stringify(status).includes(connection.headers.Authorization));
    const mcpState=await page.evaluate(()=>window.consoleApi.mcpSnapshot());
    for(const secret of secrets)assert.ok(!JSON.stringify(mcpState).includes(secret));
    const logs=JSON.stringify((await page.evaluate(()=>window.consoleApi.snapshot())).logs);
    for(const secret of [...secrets,'isolated private runtime request','isolated private runtime reply'])assert.ok(!logs.includes(secret));

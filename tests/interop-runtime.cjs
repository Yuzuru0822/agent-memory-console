    assert.equal(privateFiles.length,2);
    for(const file of privateFiles){const content=fs.readFileSync(path.join(data,'console-data',file),'utf8');for(const secret of [...secrets,'isolated private runtime request'])assert.ok(!content.includes(secret),'real OS encryption must hide private fixture bytes');}
    await page.evaluate(()=>window.consoleApi.repositoryCommit());

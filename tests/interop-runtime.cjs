    assert.equal(persisted.mcp.bindings.length,2);
    console.log('PASS interop runtime: actual Electron IPC + DPAPI and encrypted restart, safe config merge/rollback/conflict/hash/confirmation, private Git separation, two-client MCP request/reply, isolation, A2A Card/Send/Get/List/version, token revocation. No vendor model or real user config invoked. '+(packaged?'Packaged ASAR.':'Development build.'));

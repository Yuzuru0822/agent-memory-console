    assert.deepEqual(resultValue(await tool(connection,'bridge_inbox_list')),[],'sender inbox excludes outgoing tasks');
    assert.equal(resultValue(await tool(buddy,'bridge_inbox_list'))[0].id,sent.id);
    assert.equal((await tool(third,'bridge_task_get',{taskId:sent.id})).isError,true,'unrelated identity cannot read task');
    assert.equal((await tool(connection,'bridge_task_reply',{taskId:sent.id,text:'spoof',state:'completed'})).isError,true,'source cannot reply as recipient');
    assert.equal(resultValue(await tool(buddy,'bridge_task_claim',{taskId:sent.id})).delivery,'received');
    assert.equal(resultValue(await tool(buddy,'bridge_task_reply',{taskId:sent.id,text:'isolated private runtime reply',state:'completed'})).state,'completed');
    assert.equal(resultValue(await tool(connection,'bridge_task_get',{taskId:sent.id})).messages.at(-1).text,'isolated private runtime reply');
    assert.equal((await rpc(connection,'ping',{}, {Origin:'https://untrusted.example'})).status,403);
    const a2a=async(method,params,version='1.0')=>{
      const r=await fetch(`http://127.0.0.1:${port}/a2a/workbuddy`,{method:'POST',headers:{...connection.headers,'Content-Type':'application/json','A2A-Version':version},body:JSON.stringify({jsonrpc:'2.0',id:crypto.randomUUID(),method,params}),signal:AbortSignal.timeout(8000)});return r.json();
    };
    const cardResponse=await fetch(`http://127.0.0.1:${port}/a2a/workbuddy/.well-known/agent-card.json`,{headers:connection.headers});
    const card=await cardResponse.json();assert.equal(card.supportedInterfaces[0].protocolVersion,'1.0');assert.equal(card.capabilities.streaming,false);
    const a2asent=await a2a('SendMessage',{message:{messageId:'runtime-a2a-1',role:'ROLE_USER',parts:[{text:'A2A fixture request'}]},configuration:{returnImmediately:true}});
